package com.example.democode3.features.learning.model;

public class CodeBlock {

    // =====================================================
    // VALUE
    // =====================================================

    public String value;

    // =====================================================
    // EDITABLE
    // =====================================================

    public boolean editable;

    // =====================================================
    // CONSTRUCTOR
    // =====================================================

    public CodeBlock(

            String value,

            boolean editable
    ) {

        this.value = value;

        this.editable = editable;
    }
}

